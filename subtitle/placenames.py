def has_tab_place(text):
    """文字裡還有沒有頁籤編號（①～④）。"""
    return any(ch in text for ch in CIRCLED) if isinstance(text, str) else False


def for_editor(text):
    """四頁籤的說法換成剪輯器版面的說法；沒有頁籤編號的原樣回傳（同一個物件）。"""
    if not has_tab_place(text):
        return text
    for old, new in RULES:
        if old in text:
            text = text.replace(old, new)
    return text
